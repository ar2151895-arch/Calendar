// Helper to get all festivals for a specific year
export function getFestivalsForYear(year: number): Festival[] {
  const result: Festival[] = [];

  for (const def of FESTIVAL_DEFINITIONS) {
    let dateStr = '';
    let muhurat = '';
    let kabHaiNote = '';
    let kabNahinNote = def.kabNahin;

    if (def.fixedDate) {
      // Fixed solar date festivals (e.g. Republic Day, Independence Day, Christmas)
      const m = String(def.fixedDate.month).padStart(2, '0');
      const d = String(def.fixedDate.day).padStart(2, '0');
      dateStr = `${year}-${m}-${d}`;
      muhurat = 'पूरे दिन मान्य';
      kabHaiNote = `हर वर्ष ${def.fixedDate.day} ${getMonthNameHindi(def.fixedDate.month - 1)} को मनाया जाता है।`;
    } else if (def.datesByYear && def.datesByYear[year]) {
      // Exact verified date for this year
      dateStr = def.datesByYear[year].date;
      muhurat = def.datesByYear[year].muhurat;
      kabHaiNote = def.datesByYear[year].kabHaiNote || `${formatHindiDate(dateStr)} को मनाया जाएगा।`;
      if (def.datesByYear[year].kabNahinNote) {
        kabNahinNote = def.datesByYear[year].kabNahinNote!;
      }
    } else {
      // Lunisolar shift approximation for years beyond the verified table
      // Lunar year is approx 10.87 days shorter than solar year, with leap month (Adhik Maas) every ~3 years
      const baseYear = 2026;
      const baseDate = def.datesByYear?.[baseYear]?.date || `${year}-${String(def.approximateMonth || 10).padStart(2, '0')}-${String(def.approximateDay || 15).padStart(2, '0')}`;
      
      const yearDiff = year - baseYear;
      // Approximate lunar cycle shift: ~11 days earlier per year, +30 days when leap month occurs
      let dayShift = (yearDiff * -10.875) % 365;
      // Adhik maas correction: add 29.5 days approx every 2.7 years
      const leapMonthCount = Math.floor(yearDiff / 2.71);
      dayShift += leapMonthCount * 29.53;
      
      const [bY, bM, bD] = baseDate.split('-').map(Number);
      const estDate = new Date(year, bM - 1, bD);
      estDate.setDate(estDate.getDate() + Math.round(dayShift % 30));
      
      const mStr = String(estDate.getMonth() + 1).padStart(2, '0');
      const dStr = String(estDate.getDate()).padStart(2, '0');
      dateStr = `${year}-${mStr}-${dStr}`;
      muhurat = 'पंचांग अनुसार शुभ समय';
      kabHaiNote = `वर्ष ${year} में लगभग ${formatHindiDate(dateStr)} (पंचांग अनुसार)।`;
    }

    result.push({
      id: `${def.id}-${year}`,
      name: def.name,
      englishName: def.englishName,
      date: dateStr,
      category: def.category,
      color: def.color,
      badge: def.badge,
      tithi: def.tithi,
      kyaHai: def.kyaHai,
      kyunManateHain: def.kyunManateHain,
      kabHai: kabHaiNote || `${formatHindiDate(dateStr)}`,
      kabNahin: kabNahinNote,
      shubhMuhurat: muhurat || 'शुभ चौघड़िया व प्रदोष काल',
      vidhiAndDoDont: def.vidhiAndDoDont,
      isOfficialHoliday: def.isOfficialHoliday,
    });
  }

  // Sort chronologically
  return result.sort((a, b) => a.date.localeCompare(b.date));
}

export function formatHindiDate(dateStr: string): string {
  try {
    const parts = dateStr.split('-');
    if (parts.length !== 3) return dateStr;
    const year = parts[0];
    const month = parseInt(parts[1], 10) - 1;
    const day = parseInt(parts[2], 10);
    const hindiMonths = [
      'जनवरी', 'फरवरी', 'मार्च', 'अप्रैल', 'मई', 'जून',
      'जुलाई', 'अगस्त', 'सितंबर', 'अक्टूबर', 'नवंबर', 'दिसंबर'
    ];
    return `${day} ${hindiMonths[month]} ${year}`;
  } catch {
    return dateStr;
  }
}

export function getMonthNameHindi(monthIndex: number): string {
  const hindiMonths = [
    'जनवरी', 'फरवरी', 'मार्च', 'अप्रैल', 'मई', 'जून',
    'जुलाई', 'अगस्त', 'सितंबर', 'अक्टूबर', 'नवंबर', 'दिसंबर'
  ];
  return hindiMonths[monthIndex] || '';
}

