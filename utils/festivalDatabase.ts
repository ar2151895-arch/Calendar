export function formatEnglishDate(dateStr: string): string {
  try {
    const parts = dateStr.split('-');
    if (parts.length !== 3) return dateStr;
    const year = parts[0];
    const month = parseInt(parts[1], 10) - 1;
    const day = parseInt(parts[2], 10);
    const englishMonths = [
      'January', 'February', 'March', 'April', 'May', 'June',
      'July', 'August', 'September', 'October', 'November', 'December'
    ];
    return `${day} ${englishMonths[month]} ${year}`;
  } catch {
    return dateStr;
  }
}

export function formatDateBilingual(dateStr: string): string {
  const eng = formatEnglishDate(dateStr);
  const hin = formatHindiDate(dateStr);
  return `${eng} / ${hin}`;
}
